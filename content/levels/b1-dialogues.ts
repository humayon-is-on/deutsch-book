import type { Article, TextItem } from '../../src/content/types';

/**
 * The person's 30 B1 dialogues, easiest first. In each, two friends plan
 * something together (the B1 speaking task "gemeinsam etwas planen"); the
 * short everyday plans come first, the ones with more to organise later.
 * Like A2, each starts with a short description of the situation, the
 * Bangla translation opens as one block under the dialogue, and three key
 * words, Bangla only, can be bookmarked. The file calls the speakers A and
 * B; here they get names.
 */
type Line = [speaker: 'A' | 'B', de: string, bn: string];
type Word = [de: string, bn: string, article?: Article];

function dialog(
  id: string,
  title: { de: string; bn: string; en: string },
  summary: { bn: string; en: string },
  names: [a: string, b: string],
  lines: Line[],
  words: Word[],
): TextItem {
  const itemId = `b1-dialogue-${id}`;
  return {
    id: itemId,
    level: 'B1',
    module: 'dialogues',
    topic: title.de,
    title,
    situation: summary,
    lines: lines.map(([who, de, bn]) => ({ speaker: names[who === 'A' ? 0 : 1], de, bn })),
    words: words.map(([de, bn, article], i) => ({ id: `${itemId}-w${i + 1}`, de, bn, ...(article ? { article } : {}) })),
  };
}

